        // 不支持的字符显示为方框
        private static readonly int[] Missing = Parse("##### #...# #...# #...# #...# #...# #####");

        private static readonly Dictionary<char, int[]> Glyphs = CreateGlyphs();

        public static bool Contains(char c)
        {
            return Glyphs.ContainsKey(c);
        }

        /// <summary>
        /// 返回字形的点阵，每个元素是一行，低 5 位从高到低依次对应从左到右的点
        /// </summary>
        public static int[] GetGlyph(char c)
        {
            return Glyphs.TryGetValue(c, out var glyph) ? glyph : Missing;
        }

        /// <summary>
        /// 在 (x, y) 处绘制文字，字号单位为磅（按 96 DPI 换算为像素），
        /// 布局尽量与 GDI+ DrawString 使用 12 磅 Arial 时的位置和大小接近
        /// </summary>
        public static void DrawText(CommonImage image, string text, float x, float y, float fontSize, Color color)
        {
            if (string.IsNullOrEmpty(text) || fontSize <= 0)
                return;

            float em = fontSize * 96f / 72f;
            float dot = em / 10f;
            float advance = dot * (Columns + 1);
            float lineHeight = dot * (Rows + 3);
            float left = x + em * 0.1f;
            float top = y + em * 0.2f;

            var lines = text.Replace("\r", string.Empty).Split('\n');
            int maxLength = 0;
            foreach (var line in lines)
                maxLength = System.Math.Max(maxLength, line.Length);

            var mask = CoverageMask.Create(image, left, top, left + advance * maxLength, top + lineHeight * lines.Length);
            if (mask == null)
                return;

            for (int l = 0; l < lines.Length; l++)
            {
                float lineTop = top + l * lineHeight;
                for (int i = 0; i < lines[l].Length; i++)
                {
                    char c = lines[l][i];
                    if (char.IsControl(c))
                        continue;

                    var glyph = GetGlyph(c);
                    float glyphLeft = left + i * advance;
                    for (int row = 0; row < glyph.Length; row++)
                        for (int col = 0; col < Columns; col++)
                        {
                            if ((glyph[row] & (1 << (Columns - 1 - col))) == 0)
                                continue;

                            float cx = glyphLeft + col * dot;
                            float cy = lineTop + row * dot;
                            mask.Add(cx, cy, cx + dot, cy + dot);
                        }
                }
            }

            mask.Apply(image, color);
        }

        private static Dictionary<char, int[]> CreateGlyphs()
        {
            var glyphs = new Dictionary<char, int[]>();
            foreach (var (c, rows) in Definitions)
                glyphs.Add(c, Parse(rows));
            return glyphs;
        }

        private static int[] Parse(string rows)
        {
            var tokens = rows.Split(' ');
            if (tokens.Length < 7 || tokens.Length > Rows)
                throw new InvalidOperationException($"字形行数无效：{rows}");

            var glyph = new int[tokens.Length];
            for (int r = 0; r < tokens.Length; r++)
            {
                if (tokens[r].Length != Columns)
                    throw new InvalidOperationException($"字形列数无效：{rows}");

                for (int c = 0; c < Columns; c++)
                {
                    if (tokens[r][c] == '#')
                        glyph[r] |= 1 << (Columns - 1 - c);
                }
            }
            return glyph;
        }
